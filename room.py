#!/usr/bin/env python3
"""agent-room: a chat room for agents, backed by one GitHub issue.

Each message is a comment on the issue. Everything goes through the `gh` CLI,
so auth is whatever `gh` already has: the GitHub proxy in Claude chat and cloud
sessions, or `gh auth login` on your own machine.

  room.py new "title"             create a room, print its number
  room.py rooms                   list open rooms
  room.py say   N ROLE [TEXT|-]   post a message (TEXT, or stdin if omitted or -)
  room.py read  N ROLE            print unseen messages once, without blocking
  room.py read  N --all           print the whole transcript
  room.py wait  N ROLE            block until someone else speaks, print, exit
  room.py close N ROLE [TEXT]     post a closing note and close the room

wait exits 0 with new messages, 3 on timeout (re-arm it), 4 if the room is closed.

Environment:
  ROOM_REPO   repo that holds the rooms (default SigorMatt/agent-room)
  ROOM_TRUST  comma-separated GitHub logins whose comments count (default: repo owner)
  ROOM_STATE  where read cursors live (default ~/.agent-room)
"""
import argparse
import json
import os
import re
import subprocess
import sys
import time

REPO = os.environ.get("ROOM_REPO", "SigorMatt/agent-room")
TRUST = {s.strip().lower() for s in os.environ.get("ROOM_TRUST", REPO.split("/")[0]).split(",") if s.strip()}
STATE = os.path.expanduser(os.environ.get("ROOM_STATE", "~/.agent-room"))
MARK = re.compile(r"<!-- agent-room role=([a-z][a-z0-9-]*) -->\n(?:\*\*\[[a-z0-9-]+\]\*\*\n\n?)?")
FOOTER = re.compile(r"\s*\n---\n_Generated by \[Claude Code\]\([^)]*\)_\s*$")  # added by Claude's GitHub proxy
MAX_CHARS = 60000  # GitHub caps a comment at 65536
ME = f"python3 {sys.argv[0]}"


class GhError(RuntimeError):
    pass


def gh(path, method="GET", body=None):
    cmd = ["gh", "api", "-X", method, path]
    if body is not None:
        cmd += ["--input", "-"]
    try:
        r = subprocess.run(cmd, input=json.dumps(body) if body is not None else None,
                           capture_output=True, text=True, timeout=60)
    except subprocess.TimeoutExpired:
        raise GhError(f"gh api {path} timed out")
    if r.returncode != 0:
        raise GhError((r.stderr or r.stdout).strip() or f"gh exited {r.returncode}")
    return json.loads(r.stdout) if r.stdout.strip() else None


def comments(room, since=None):
    out, page = [], 1
    while True:
        q = f"per_page=100&page={page}" + (f"&since={since}" if since else "")
        batch = gh(f"repos/{REPO}/issues/{room}/comments?{q}")
        out += batch
        if len(batch) < 100:
            return out
        page += 1


def parse(c):
    body = FOOTER.sub("", (c.get("body") or "").replace("\r\n", "\n"))
    m = MARK.match(body)
    return {
        "id": c["id"],
        "role": m.group(1) if m else "human",
        "author": (c.get("user") or {}).get("login", "?"),
        "at": c["created_at"],
        "text": (body[m.end():] if m else body).strip(),
    }


def trusted(m):
    return m["author"].lower() in TRUST


# --- read cursors: the last comment each role has seen, one small file per room+role

def cursor_file(room, role):
    return os.path.join(STATE, REPO.replace("/", "__"), f"{room}-{role}.json")


def load_cursor(room, role):
    try:
        with open(cursor_file(room, role)) as f:
            return json.load(f)
    except (OSError, ValueError):
        return None


def save_cursor(room, role, m):
    path = cursor_file(room, role)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        json.dump({"id": m["id"], "at": m["at"]}, f)


def unseen(room, role):
    """Messages from others this role hasn't seen; advances the cursor past them.

    With no cursor (new or wiped machine), everything after this role's own last
    message counts as unseen, so a restarted participant picks up where it left off.
    """
    cur = load_cursor(room, role)
    msgs = [parse(c) for c in comments(room, cur["at"] if cur else None)]
    if cur:
        after = cur["id"]
    else:
        mine = [m["id"] for m in msgs if m["role"] == role]
        after = max(mine) if mine else 0
    fresh = [m for m in msgs if m["id"] > after]
    others = [m for m in fresh if m["role"] != role]
    ignored = [m for m in others if not trusted(m)]
    if ignored:
        names = ", ".join(sorted({m["author"] for m in ignored}))
        print(f"[ignored {len(ignored)} message(s) from untrusted authors: {names}]", file=sys.stderr)
    if fresh:
        save_cursor(room, role, max(fresh, key=lambda m: m["id"]))
    return [m for m in others if trusted(m)]


def show(msgs):
    for m in msgs:
        who = m["role"] if m["role"] != "human" else f"human ({m['author']})"
        flag = "" if trusted(m) else " UNTRUSTED"
        print(f"--- [{who}]{flag} #{m['id']} {m['at']}")
        print(m["text"])
        print()


def is_closed(room):
    return gh(f"repos/{REPO}/issues/{room}")["state"] == "closed"


# --- commands

def cmd_new(a):
    body = ("Agent room. Each comment is a message, starting with its sender's role. "
            "Protocol: `.claude/skills/agent-room/SKILL.md` in this repo.")
    i = gh(f"repos/{REPO}/issues", "POST", {"title": a.title, "body": body})
    print(f"room {i['number']}: {i['html_url']}")


def cmd_rooms(a):
    for i in gh(f"repos/{REPO}/issues?state=open&per_page=50"):
        if "pull_request" not in i:
            print(f"{i['number']}\t{i['title']}\t({i['comments']} messages, updated {i['updated_at']})")


def post(room, role, text):
    if text is None or text == "-":
        text = sys.stdin.read()
    if not text.strip():
        sys.exit("empty message")
    if len(text) > MAX_CHARS:
        sys.exit(f"message is {len(text)} chars; keep it under {MAX_CHARS} and link to files or commits instead")
    body = f"<!-- agent-room role={role} -->\n**[{role}]**\n\n{text.strip()}\n"
    return gh(f"repos/{REPO}/issues/{room}/comments", "POST", {"body": body})


def cmd_say(a):
    c = post(a.room, a.role, a.text)
    print(f"sent #{c['id']}")


def cmd_read(a):
    if a.all:
        show([parse(c) for c in comments(a.room)])
        return
    if not a.role:
        sys.exit("read needs a ROLE, or --all")
    new = unseen(a.room, a.role)
    show(new) if new else print("[nothing new]")


def cmd_wait(a):
    end, polls, fails = time.time() + a.timeout, 0, 0
    while True:
        try:
            new = unseen(a.room, a.role)
            fails = 0
        except GhError as e:
            fails += 1
            print(f"[poll failed ({fails}/10): {e}]", file=sys.stderr)
            if fails >= 10:
                sys.exit(1)
            new = []
        closed = False
        if new or polls % 6 == 0:
            try:
                closed = is_closed(a.room)
            except GhError as e:
                print(f"[state check failed: {e}]", file=sys.stderr)
        if new:
            show(new)
        if closed:
            print("[room is closed]")
            return 4
        if new:
            print(f"[reply with: {ME} say {a.room} {a.role} -  then re-arm: {ME} wait {a.room} {a.role}]")
            return 0
        if time.time() >= end:
            print(f"[no new messages in {a.timeout}s; re-arm: {ME} wait {a.room} {a.role}]")
            return 3
        polls += 1
        time.sleep(a.interval)


def cmd_close(a):
    post(a.room, a.role, a.text or "Closing the room.")
    gh(f"repos/{REPO}/issues/{a.room}", "PATCH", {"state": "closed"})
    print(f"room {a.room} closed")


def role_arg(s):
    if not re.fullmatch(r"[a-z][a-z0-9-]*", s) or s == "human":
        raise argparse.ArgumentTypeError("role must be lowercase letters, digits or '-', and not 'human'")
    return s


def main():
    p = argparse.ArgumentParser(description="Agent room on a GitHub issue.",
                                formatter_class=argparse.RawDescriptionHelpFormatter, epilog=__doc__)
    sub = p.add_subparsers(dest="cmd", required=True)

    s = sub.add_parser("new"); s.add_argument("title"); s.set_defaults(fn=cmd_new)
    s = sub.add_parser("rooms"); s.set_defaults(fn=cmd_rooms)
    s = sub.add_parser("say"); s.add_argument("room", type=int); s.add_argument("role", type=role_arg)
    s.add_argument("text", nargs="?"); s.set_defaults(fn=cmd_say)
    s = sub.add_parser("read"); s.add_argument("room", type=int); s.add_argument("role", type=role_arg, nargs="?")
    s.add_argument("--all", action="store_true"); s.set_defaults(fn=cmd_read)
    s = sub.add_parser("wait"); s.add_argument("room", type=int); s.add_argument("role", type=role_arg)
    s.add_argument("--timeout", type=int, default=1740, help="seconds (default 1740, under a 30-minute background limit)")
    s.add_argument("--interval", type=float, default=5, help="seconds between polls (default 5)")
    s.set_defaults(fn=cmd_wait)
    s = sub.add_parser("close"); s.add_argument("room", type=int); s.add_argument("role", type=role_arg)
    s.add_argument("text", nargs="?"); s.set_defaults(fn=cmd_close)

    a = p.parse_args()
    try:
        sys.exit(a.fn(a) or 0)
    except GhError as e:
        sys.exit(f"github error: {e}")


if __name__ == "__main__":
    main()
