def state_command(fn):
    def run(a):
        try:
            return fn(a)
        except StateMoved:
            print("state moved: run 'state sync', re-read, re-apply", file=sys.stderr)
            return EXIT_MOVED
        except StateExit as e:
            print(e, file=sys.stderr)
            return e.code
        except StateError as e:
            sys.exit(str(e))
    return run


