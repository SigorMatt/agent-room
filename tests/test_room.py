    assert r.returncode != 0 and f"not in room {n}" in r.stderr, r.stderr
    assert run("cursor", n, "lead", **joiner).stdout.strip() == gap, "a refused --from leaves the cursor alone"
    r = run("read", n, "lead", "--from", "999999", check=False, **joiner)
    assert r.returncode != 0 and "github error" in r.stderr, r.stderr
    r = run("read", n, "lead", "--from", "latest", check=False, **joiner)
    assert r.returncode == 2 and "comment ID" in r.stderr, r.stderr


