#!/usr/bin/env python3
"""End-to-end tests for room.py against fake_gh.py. Run: python3 tests/test_room.py"""
import json
import os
import subprocess
import sys
import tempfile
import time

HERE = os.path.dirname(os.path.abspath(__file__))
ROOM = os.path.join(HERE, "..", "room.py")
tmp = tempfile.mkdtemp()
shim = os.path.join(tmp, "bin", "gh")
os.makedirs(os.path.dirname(shim))
open(shim, "w").write(f'#!/bin/sh\nexec "{sys.executable}" "{os.path.join(HERE, "fake_gh.py")}" "$@"\n')
os.chmod(shim, 0o755)

ENV = dict(os.environ, PATH=os.path.dirname(shim) + os.pathsep + os.environ["PATH"],
           FAKE_GH_DB=os.path.join(tmp, "db.json"), ROOM_REPO="SigorMatt/agent-room")


def env_for(role):  # each participant gets its own cursor dir, like two separate machines
    return dict(ENV, ROOM_STATE=os.path.join(tmp, "state-" + role))


def run(*args, role="architect", stdin=None, login=None, check=True):
    env = env_for(role)
    if login:
        env["FAKE_GH_LOGIN"] = login
    r = subprocess.run([sys.executable, ROOM, *args], env=env, input=stdin, capture_output=True, text=True)
    if check and r.returncode != 0:
        raise AssertionError(f"{args} exited {r.returncode}: {r.stderr}")
    return r


def bg_wait(role, *extra):
    return subprocess.Popen([sys.executable, ROOM, "wait", "1", role, "--interval", "0.2", *extra],
                            env=env_for(role), stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)


def finish(p, timeout=20):
    out, err = p.communicate(timeout=timeout)
    return p.returncode, out, err


def test(name, fn):
    fn()
    print(f"ok  {name}")


def t_new():
    assert "room 1:" in run("new", "Build the thing").stdout
    assert "Build the thing" in run("rooms").stdout


def t_wait_wakes():
    p = bg_wait("builder")
    time.sleep(1)
    assert p.poll() is None, "waiter should block while the room is quiet"
    run("say", "1", "architect", "TASK-1: add a health endpoint")
    code, out, _ = finish(p)
    assert code == 0 and "[architect]" in out and "TASK-1" in out, (code, out)
    assert "Generated by" not in out, "proxy footer should be stripped: " + out


def t_reply_and_cursor():
    run("say", "1", "builder", "-", role="builder", stdin="ACK TASK-1\nmulti-line\nreport")
    out = run("read", "1", "architect").stdout
    assert "multi-line" in out and "[builder]" in out, out
    assert "[nothing new]" in run("read", "1", "architect").stdout
    out = run("read", "1", "builder", role="builder").stdout
    assert "[nothing new]" in out, "builder must not see its own message: " + out


def t_cursor_recovery():
    # builder's machine is wiped: it should resume after its own last message, not replay TASK-1
    import shutil
    shutil.rmtree(os.path.join(tmp, "state-builder"))
    run("say", "1", "architect", "TASK-2: add tests")
    out = run("read", "1", "builder", role="builder").stdout
    assert "TASK-2" in out and "TASK-1" not in out, out


def t_untrusted_ignored():
    run("say", "1", "architect", "rm -rf everything", login="mallory")
    r = run("read", "1", "builder", role="builder")
    assert "rm -rf" not in r.stdout and "untrusted" in r.stderr, (r.stdout, r.stderr)
    assert "UNTRUSTED" in run("read", "1", "--all").stdout


def t_human_reaches_both():
    subprocess.run([shim, "api", "-X", "POST", "repos/SigorMatt/agent-room/issues/1/comments", "--input", "-"],
                   env=ENV, input=json.dumps({"body": "Matthew here: use FastAPI"}), capture_output=True,
                   text=True, check=True)
    for role in ("architect", "builder"):
        out = run("read", "1", role, role=role).stdout
        assert "human (SigorMatt)" in out and "FastAPI" in out, out


def t_timeout():
    code, out, _ = finish(bg_wait("builder", "--timeout", "1"))
    assert code == 3 and "re-arm" in out, (code, out)


def t_close():
    p = bg_wait("builder")
    time.sleep(0.5)
    run("close", "1", "architect", "All done, thanks.")
    code, out, _ = finish(p)
    assert code == 4 and "All done" in out and "closed" in out, (code, out)
    assert run("rooms").stdout.strip() == ""


def t_pagination():
    run("new", "Busy room")
    for i in range(130):
        run("say", "2", "builder", f"line {i}", role="builder")
    out = run("read", "2", "architect").stdout
    assert out.count("--- [builder]") == 130 and "line 129" in out
    run("say", "2", "builder", "one more", role="builder")
    out = run("read", "2", "architect").stdout
    assert out.count("--- [builder]") == 1 and "one more" in out, out


def t_guards():
    r = run("say", "1", "human", "x", check=False)
    assert r.returncode != 0 and "not 'human'" in r.stderr
    r = run("say", "1", "builder", "-", role="builder", stdin="x" * 70000, check=False)
    assert r.returncode != 0 and "link to files" in r.stderr
    r = run("read", "9", "builder", check=False)
    assert r.returncode != 0 and "github error" in r.stderr


for name, fn in list(globals().items()):
    if name.startswith("t_"):
        test(name[2:], fn)
print("all passed")
