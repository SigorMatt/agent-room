def env_for(role):  # each participant gets its own cursor dir, like two separate machines
    return dict(ENV, ROOM_STATE=os.path.join(tmp, "state-" + role), ROOM_SESSION="s1")


def run(*args, role="architect", stdin=None, login=None, check=True, cwd=None, **env_overrides):
    env = env_for(role)
    if login:
        env["FAKE_GH_LOGIN"] = login
    for k, v in env_overrides.items():
        if v is None:
            env.pop(k, None)
        else:
            env[k] = v
    r = subprocess.run([sys.executable, ROOM, *args], env=env, input=stdin, capture_output=True, text=True, cwd=cwd)
    if check and r.returncode != 0:
        raise AssertionError(f"{args} exited {r.returncode}: {r.stderr}")
    return r


def bg_wait(role, *extra, room="1", **env):
    return subprocess.Popen([sys.executable, ROOM, "wait", room, role, "--interval", "0.2", *extra],
                            env=dict(env_for(role), **env), stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)


def finish(p, timeout=20):
    out, err = p.communicate(timeout=timeout)
    return p.returncode, out, err


def test(name, fn):
    fn()
    print(f"ok  {name}")


