def load_room_module():  # for unit tests of pure helpers; importing room.py runs nothing
    sys.dont_write_bytecode = True  # no __pycache__ beside room.py
    spec = importlib.util.spec_from_file_location("room_under_test", ROOM)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def new_room(title, script=ROOM):
    r = subprocess.run([sys.executable, script, "new", title], env=env_for("architect"), capture_output=True, text=True)
    assert r.returncode == 0, r.stderr
    return re.search(r"room (\d+) in", r.stdout).group(1)


def sent_id(r):
    return re.search(r"sent #(\d+)", r.stdout).group(1)


def issue(n):
    with open(ENV["FAKE_GH_DB"]) as f:
        return json.load(f)["repos"]["SigorMatt/agent-room"]["issues"][n]


